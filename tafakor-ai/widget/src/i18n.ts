export type Lang = 'fa' | 'en';

export function lang(): Lang {
  return document.documentElement.lang === 'en' ? 'en' : 'fa';
}

export function t(key: Exclude<keyof Dict, 'actions'>, params?: Record<string, string | number>): string {
  let s = (lang() === 'fa' ? fa : en)[key] as string;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function actionName(a: string): string {
  return (lang() === 'fa' ? fa : en).actions[a] ?? a;
}

/** Formats digits for display in the current language. */
export function num(s: string | number): string {
  const str = String(s);
  let grouped = str;
  if (/^-?\d+(\.\d+)?$/.test(str)) {
    const [i, f] = str.split('.');
    grouped = i.replace(/\B(?=(\d{3})+(?!\d))/g, ',') + (f ? '.' + f : '');
  }
  if (lang() !== 'fa') return grouped;
  return grouped.replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[Number(d)]).replace(/,/g, '٬');
}
